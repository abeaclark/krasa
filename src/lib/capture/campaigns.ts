import type { Brand } from "@/lib/email/brands";
import { brandUrl } from "@/lib/email/brands";
import { BODY, FONT, esc, h1, p } from "@/lib/email/kit";
import { h2, hr, link, productCard, resolveProduct } from "@/lib/email/productBlocks";
import type { EmailProduct } from "./product";
import { ageAnswer, stepInput, type Built } from "./sequences";
import type { SubscriberRow } from "./store";
import { SK_CHRISTMAS } from "./campaignData";

/**
 * One-off seasonal sends to a site's whole popup list ("broadcasts").
 *
 * Each campaign goes out once per subscriber (capture_sends key `camp:<id>`),
 * only between `sendAt` and `until`, and only to active, marketing-OK people
 * who signed up before `sendAt` (someone who joins mid-send gets the sequence,
 * not a broadcast written for the existing list). The cron sends in batches, so
 * a big list drains over a few runs; anyone not reached by `until` is skipped
 * rather than mailed a stale "Black Friday" email.
 *
 * Content is segmented by the one-tap age answer: the ages 6–12 Christmas
 * puzzle book isn't shown to the 2–5 crowd, and the gift-guide links match the
 * ages they told us. Product data comes from the Sunlight catalog
 * (campaignData.ts, generated by sunlight's scripts/email-campaign-data.ts).
 */

export interface CampaignInput {
  brand: Brand;
  sub: SubscriberRow;
  /** Their matched book in their age edition (links resolved), if they have one. */
  edition: EmailProduct | null;
  paid: string[];
}

export interface Campaign {
  id: string;
  site: string;
  sendAt: Date;
  until: Date;
  build(i: CampaignInput): Built | null;
}

type Band = "2-5" | "4-7" | "7+";

function bandOf(sub: SubscriberRow): Band | null {
  const a = ageAnswer(sub)?.replace(/[–—]/g, "-").trim();
  return a === "2-5" || a === "4-7" || a === "7+" ? a : null;
}

/** "Ages 2, 3, 4 and 5" style links to the gift guides that fit the answer. */
function giftGuides(b: Brand, band: Band | null): { html: string; text: string[] } {
  const ages = band ? SK_CHRISTMAS.giftAges[band] : [];
  const items = ages
    .map((age) => ({ age, url: brandUrl(b, `/gifts-for-${age}-year-olds`) }))
    .filter((x): x is { age: number; url: string } => !!x.url);
  const hub = brandUrl(b, "/gifts");
  if (!items.length) {
    return hub
      ? { html: p(`${link(b, "Gift guides for every age", hub)}, from 2 to 12.`), text: [`Gift guides for every age: ${hub}`] }
      : { html: "", text: [] };
  }
  return {
    html: p(`Gift guides: ${items.map((x) => link(b, `${x.age}-year-olds`, x.url)).join(" · ")}`),
    text: ["Gift guides:", ...items.map((x) => `- ${x.age}-year-olds: ${x.url}`)],
  };
}

function freePrintables(b: Brand): { html: string; text: string[] } {
  const items = SK_CHRISTMAS.printables
    .map((x) => ({ ...x, url: brandUrl(b, x.path) }))
    .filter((x): x is typeof x & { url: string } => !!x.url);
  if (!items.length) return { html: "", text: [] };
  return {
    html: [
      h2("Free Christmas printables"),
      `<ul style="margin:0 0 16px;padding-left:20px;font-family:${FONT};font-size:15px;line-height:1.6;color:${BODY};">${items
        .map((x) => `<li style="margin:0 0 6px;">${link(b, x.label, x.url)}: ${esc(x.note)}</li>`)
        .join("")}</ul>`,
    ].join("\n"),
    text: ["Free Christmas printables:", ...items.map((x) => `- ${x.label} (${x.note}): ${x.url}`)],
  };
}

function cards(b: Brand, products: (EmailProduct | null)[], paid: string[], opts: { pdfOnly?: boolean } = {}) {
  const seen = new Set<string>();
  const out: { html: string; text: string[] }[] = [];
  for (const raw of products) {
    if (!raw || paid.includes(raw.id) || seen.has(raw.id)) continue;
    const prod = resolveProduct(b, raw);
    if (!prod) continue;
    if (opts.pdfOnly && !prod.pdfUrl) continue;
    seen.add(raw.id);
    out.push(productCard(b, opts.pdfOnly ? { ...prod, amazonUrl: null } : prod));
  }
  return out;
}

function assemble(head: string[], headText: string[], parts: { html: string; text: string[] }[]): { html: string; text: string[] } {
  const html = [...head];
  const text = [...headText];
  parts.forEach((part, i) => {
    if (!part.html) return;
    if (i > 0) html.push(hr);
    html.push(part.html);
    text.push("", ...part.text);
  });
  return { html: html.join("\n"), text };
}

const blackFriday2026: Campaign = {
  id: "sk-2026-black-friday",
  site: "sunlightkids.com",
  sendAt: new Date("2026-11-27T17:00:00Z"), // Fri Nov 27, 7:00 AM HST / 12:00 PM ET
  until: new Date("2026-11-30T17:00:00Z"),
  build({ brand: b, sub, edition, paid }) {
    const band = bandOf(sub);
    const products = [
      band === "2-5" ? null : SK_CHRISTMAS.book, // ages 6–12
      SK_CHRISTMAS.pack, // ages 3 to adult
      edition,
    ];
    const productCards = cards(b, products, paid);
    if (!productCards.length) return null;
    const lead =
      "Here's what we'd put on a Christmas list for kids. Paperbacks ship from Amazon; every Download & Print PDF is emailed to you right after checkout, so it still works on Christmas Eve.";
    const gifts = giftGuides(b, band);
    const free = freePrintables(b);
    const body = assemble(
      [h1("Christmas books and games for kids"), p(esc(lead))],
      ["Christmas books and games for kids", "", lead],
      [...productCards, { html: [h2("More gift ideas"), gifts.html].join("\n"), text: ["More gift ideas", ...gifts.text] }, free],
    );
    return {
      subject: "Christmas books and games for kids, by age",
      preheader: "Paperbacks ship from Amazon. PDFs print the same day.",
      ...body,
    };
  },
};

const lastMinute2026: Campaign = {
  id: "sk-2026-last-minute-pdf",
  site: "sunlightkids.com",
  sendAt: new Date("2026-12-21T17:00:00Z"), // Mon Dec 21, 7:00 AM HST / 12:00 PM ET
  until: new Date("2026-12-24T17:00:00Z"),
  build({ brand: b, sub, edition, paid }) {
    const band = bandOf(sub);
    const productCards = cards(b, [SK_CHRISTMAS.pack, band === "2-5" ? null : SK_CHRISTMAS.book, edition], paid, {
      pdfOnly: true,
    });
    if (!productCards.length) return null;
    const lead =
      "Every Download & Print PDF is emailed to you right after checkout. Print it tonight, wrap it tomorrow, and nobody has to wait on a delivery.";
    const free = freePrintables(b);
    const body = assemble(
      [h1("Cutting it close? Print it instead."), p(esc(lead))],
      ["Cutting it close? Print it instead.", "", lead],
      [...productCards, free],
    );
    return {
      subject: "Cutting it close? These print at home tonight",
      preheader: "Christmas games and activity books as $4.99 PDFs, in your inbox in a minute.",
      ...body,
    };
  },
};

export const CAMPAIGNS: Campaign[] = [blackFriday2026, lastMinute2026];

export function activeCampaigns(now: Date, list: Campaign[] = CAMPAIGNS): Campaign[] {
  return list.filter((c) => now >= c.sendAt && now < c.until);
}

/** The subscriber's own book in their age edition, for a campaign. */
export function campaignEdition(brand: Brand, sub: SubscriberRow, paid: string[]): EmailProduct | null {
  return sub.context ? (stepInput(brand, sub, paid)?.edition ?? null) : null;
}
